import { randomBytes } from "node:crypto";
import { expect, test } from "@playwright/test";
import { readdir, readFile, rm } from "node:fs/promises";
import { E2E_EMAIL, E2E_PASSWORD } from "./fixtures";

const sink = "/tmp/calu-mail-e2e";

async function latestLink() {
  const files = (await readdir(sink)).filter((name) => name.endsWith(".txt")).sort();
  const text = await readFile(`${sink}/${files.at(-1)}`, "utf8");
  const link = text.split("\n").find((line) => line.startsWith("http"));
  if (!link) throw new Error("missing verification link");
  return link;
}

test("registro, proforma en USD y ticket", async ({ page }) => {
  await rm(sink, { recursive: true, force: true });
  const email = `cliente-${Date.now()}@example.com`;
  const password = `Pw-${randomBytes(9).toString("hex")}`;
  await page.goto("/cuenta/registro");
  await page.getByLabel("Nombre").fill("Cliente Prueba");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña").fill(password);
  await page.getByRole("button", { name: "Crear cuenta" }).click();
  await expect(page.getByText("Cuenta creada")).toBeVisible();
  const verify = await latestLink();
  expect(verify).not.toContain(email + password);
  await page.goto(verify);
  await page.goto("/cuenta/entrar");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña").fill(password);
  await page.getByRole("button", { name: "Entrar" }).click();
  await expect(page).toHaveURL(/\/cuenta$/);
  await page.goto("/cuenta/contratar?plan=wh0");
  await expect(page.getByRole("heading", { name: "Calu Starter" })).toBeVisible();
  await expect(page.getByTestId("list-price")).toContainText("3,99 USD");
  await expect(page.getByTestId("list-price")).not.toContainText("399 USD");
  await expect(page.getByTestId("list-price")).not.toContainText("centavos");
  await expect(page.getByText("Puerto Rico").first()).toBeVisible();
  await expect(page.getByText("proforma", { exact: false }).first()).toBeVisible();
  await page.getByRole("button", { name: "Crear pedido" }).click();
  await expect(page.getByRole("status")).toContainText("3,99 USD");
  await expect(page.getByRole("status")).toContainText("proforma");
  await expect(page.getByText("399 USD", { exact: true })).toHaveCount(0);
  await page.getByTestId("list-price").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-order.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "Calu Starter" })).toBeVisible();
  await expect(page.getByTestId("list-price")).toContainText("3,99 USD");
  await page.getByTestId("list-price").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-order-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/cuenta");
  await expect(page.getByRole("cell", { name: "3,99 USD" }).first()).toBeVisible();
  await expect(page.getByRole("cell", { name: "Proforma, no cobrable" })).toBeVisible();
  await expect(page.getByText("399 USD", { exact: true })).toHaveCount(0);
  await page.getByRole("heading", { name: "Facturas", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-account.png" });
  await page.goto("/admin/login");
  await page.locator('input[type="email"]').fill(E2E_EMAIL);
  await page.locator('input[type="password"]').fill(E2E_PASSWORD);
  await page.locator("form button.btn").click();
  await page.waitForURL("**/admin");
  await expect(page.getByRole("navigation", { name: "Admin" }).getByRole("link", { name: "Clientes" })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Admin" }).getByRole("link", { name: "Pagos" })).toBeVisible();
  await page.getByRole("navigation", { name: "Admin" }).getByRole("link", { name: "Clientes" }).click();
  await expect(page).toHaveURL(/\/admin\/clientes$/);
  await expect(page.getByRole("heading", { level: 1, name: "Clientes" })).toBeVisible();
  await expect(page.getByRole("cell", { name: "3,99 USD" }).first()).toBeVisible();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-admin-clientes.png" });
  await page.getByRole("navigation", { name: "Admin" }).getByRole("link", { name: "Pagos" }).click();
  await expect(page).toHaveURL(/\/admin\/pagos$/);
  await expect(page.getByRole("heading", { level: 1, name: "Pagos" })).toBeVisible();
  await expect(page.getByRole("cell", { name: "3,99 USD" }).first()).toBeVisible();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-admin-pagos.png" });
  await page.goto("/admin/comercio");
  await expect(page.getByRole("cell", { name: "3,99 USD" }).first()).toBeVisible();
  await expect(page.getByRole("cell", { name: "Proforma, no cobrable" }).first()).toBeVisible();
  await expect(page.getByText("Pago bloqueado").first()).toBeVisible();
  await expect(page.getByText("Puerto Rico").first()).toBeVisible();
  await expect(page.getByRole("button", { name: "Confirmar pago manual" })).toHaveCount(0);
  await expect(page.getByText("No hay servicios")).toBeVisible();
  await expect(page.getByText("399 USD", { exact: true })).toHaveCount(0);
  await expect(page.getByText(/11[,.]5|IVU/i)).toHaveCount(0);
  await page.getByRole("heading", { level: 2, name: "Pagos" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-admin-commerce.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByText("3,99 USD").first()).toBeVisible();
  await page.getByRole("heading", { level: 1, name: "Comercio" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/opt/cursor/artifacts/e2e-admin-commerce-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.context().clearCookies();
  await page.goto("/cuenta/entrar");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña").fill(password);
  await page.getByRole("button", { name: "Entrar" }).click();
  await expect(page).toHaveURL(/\/cuenta$/);
  await page.goto("/cuenta/tickets");
  await page.getByLabel("Asunto").fill("Duda de alta");
  await page.getByLabel("Mensaje").fill("¿Cuándo queda activo?");
  await page.getByRole("button", { name: "Abrir ticket" }).click();
  await expect(page.getByRole("status")).toContainText("Ticket abierto");
});
